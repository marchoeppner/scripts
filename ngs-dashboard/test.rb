            retry # This retries from the start of the begin block
        else
            abort("Quitting... #{e.inspect}")
        end
    end
end

def compress_string(data)

    compressed_data = Zlib::Deflate.deflate(data)
    encoded_data = Base64.encode64(compressed_data)

    return encoded_data

end

